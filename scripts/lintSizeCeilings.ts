/**
 * Per-file line ceilings for the size-ceiling burn-down baseline (docs/07-conventions.md — Lint-aligned
 * conventions). eslint.config.mjs holds every file in eslint.size-baseline.mjs to `warn` instead of
 * `error`, so nothing in lint stops a baselined file from growing. scripts/lintSizeCeilings.json records
 * one line ceiling per baselined file: a file over the floor is recorded at its line count plus the
 * headroom, a file within the floor at the floor. A file may not exceed its ceiling, and a ceiling more
 * than the slack above the ceiling the file's current length earns is stale and must be lowered to it.
 * Ceilings are never raised and no path is added to the baseline: scripts/checkSizeBaselineShrinks.ts
 * refuses both by comparing the head with its merge base on origin/main (findSizeBaselineGrowth). Generated files listed in
 * GENERATED_SIZE_EXEMPTIONS carry no ceiling: their size follows their generator's input.
 */

import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

/** The `max-lines` limit; no ceiling sits below it and a ceiling at it is never stale. */
export const SIZE_CEILING_FLOOR = 600;
/** Lines a file already over the floor may grow past its recorded length before code must move out. */
export const SIZE_CEILING_HEADROOM = 50;
/** How far a ceiling may sit above the ceiling a file's length earns before it must be lowered. */
export const SIZE_CEILING_SLACK = 100;

export const SIZE_CEILINGS_PATH = 'scripts/lintSizeCeilings.json';

export type GeneratedSizeExemption = { path: string; generator: string };

/**
 * Baselined files written by a generator, which grow with the generator's input. Each file must name its
 * generator in its header (`Generated by <generator>`); the baseline spec checks that and that both exist.
 */
export const GENERATED_SIZE_EXEMPTIONS: readonly GeneratedSizeExemption[] = [
    {
        path: 'src/modules/Command/useCases/versionedCommandArgumentKeys.ts',
        generator: 'scripts/generateVersionedCommandArgumentSchemas.mjs',
    },
];

export type SizeCeilingViolation =
    | { kind: 'missing-ceiling'; path: string; lines: number }
    | { kind: 'unlisted-ceiling'; path: string }
    | { kind: 'exempt-ceiling'; path: string }
    | { kind: 'stale-exemption'; path: string }
    | { kind: 'over-ceiling'; path: string; lines: number; ceiling: number }
    | { kind: 'stale-ceiling'; path: string; lines: number; ceiling: number }
    | { kind: 'below-floor'; path: string; ceiling: number };

export type SizeCeilingInputs = {
    baselineFiles: readonly string[];
    ceilings: Readonly<Record<string, number>>;
    exemptFiles: readonly string[];
    lineCount: (path: string) => number;
};

/** The ceiling a file of `lines` lines should carry: its length plus the headroom once over the floor, else the floor. */
export function expectedSizeCeiling(lines: number): number {
    return lines > SIZE_CEILING_FLOOR ? lines + SIZE_CEILING_HEADROOM : SIZE_CEILING_FLOOR;
}

function isValidCeiling(ceiling: number): boolean {
    return Number.isSafeInteger(ceiling) && ceiling >= SIZE_CEILING_FLOOR;
}

function checkBaselineFile(path: string, inputs: SizeCeilingInputs): SizeCeilingViolation | undefined {
    const ceiling = Object.hasOwn(inputs.ceilings, path) ? inputs.ceilings[path] : undefined;
    if (ceiling === undefined) {
        return { kind: 'missing-ceiling', path, lines: inputs.lineCount(path) };
    }
    if (!isValidCeiling(ceiling)) {
        return { kind: 'below-floor', path, ceiling };
    }
    const lines = inputs.lineCount(path);
    if (lines > ceiling) {
        return { kind: 'over-ceiling', path, lines, ceiling };
    }
    if (ceiling > SIZE_CEILING_FLOOR && ceiling - expectedSizeCeiling(lines) > SIZE_CEILING_SLACK) {
        return { kind: 'stale-ceiling', path, lines, ceiling };
    }
    return undefined;
}

/** Every way the recorded ceilings disagree with the baseline and the files' current lengths. */
export function findSizeCeilingViolations(inputs: SizeCeilingInputs): SizeCeilingViolation[] {
    const baseline = new Set(inputs.baselineFiles);
    const exempt = new Set(inputs.exemptFiles);
    const fileViolations = inputs.baselineFiles
        .filter((path) => !exempt.has(path))
        .flatMap((path) => checkBaselineFile(path, inputs) ?? []);
    return [
        ...fileViolations,
        ...findStrayCeilings(inputs.ceilings, baseline, exempt),
        ...findStaleExemptions(inputs.exemptFiles, baseline),
    ];
}

function findStrayCeilings(
    ceilings: Readonly<Record<string, number>>,
    baseline: ReadonlySet<string>,
    exempt: ReadonlySet<string>
): SizeCeilingViolation[] {
    return Object.keys(ceilings).flatMap((path): SizeCeilingViolation[] => {
        if (exempt.has(path)) {
            return [{ kind: 'exempt-ceiling', path }];
        }
        return baseline.has(path) ? [] : [{ kind: 'unlisted-ceiling', path }];
    });
}

function findStaleExemptions(exemptFiles: readonly string[], baseline: ReadonlySet<string>): SizeCeilingViolation[] {
    return exemptFiles
        .filter((path, index) => !baseline.has(path) && exemptFiles.indexOf(path) === index)
        .map((path): SizeCeilingViolation => ({ kind: 'stale-exemption', path }));
}

/** The instruction a future author reads when the ceilings check fails. */
export function describeSizeCeilingViolation(violation: SizeCeilingViolation): string {
    switch (violation.kind) {
        case 'missing-ceiling':
            return `${violation.path}: baselined with no ceiling in ${SIZE_CEILINGS_PATH}; insert it in sorted position with ${expectedSizeCeiling(violation.lines)} (it has ${violation.lines} lines).`;
        case 'unlisted-ceiling':
            return `${violation.path}: has a ceiling in ${SIZE_CEILINGS_PATH} but is not in eslint.size-baseline.mjs; remove the entry.`;
        case 'exempt-ceiling':
            return `${violation.path}: is a generated file in GENERATED_SIZE_EXEMPTIONS and takes no ceiling; remove its entry from ${SIZE_CEILINGS_PATH}.`;
        case 'stale-exemption':
            return `${violation.path}: is in GENERATED_SIZE_EXEMPTIONS (scripts/lintSizeCeilings.ts) but not in eslint.size-baseline.mjs; remove the exemption.`;
        case 'over-ceiling':
            return `${violation.path}: ${violation.lines} lines exceeds its ceiling of ${violation.ceiling} by ${violation.lines - violation.ceiling}; move code into a new file (new files are held to the size rules) until it has at most ${violation.ceiling} lines. Ceilings are never raised.`;
        case 'stale-ceiling':
            return `${violation.path}: ceiling ${violation.ceiling} sits more than ${SIZE_CEILING_SLACK} above ${expectedSizeCeiling(violation.lines)}, the ceiling its ${violation.lines} lines earn; lower it to ${expectedSizeCeiling(violation.lines)} in ${SIZE_CEILINGS_PATH}.`;
        case 'below-floor':
            return `${violation.path}: ceiling ${violation.ceiling} is not a whole number of at least ${SIZE_CEILING_FLOOR}; record the ceiling the file's length earns: its line count plus ${SIZE_CEILING_HEADROOM} when over ${SIZE_CEILING_FLOOR} lines, else ${SIZE_CEILING_FLOOR}.`;
        default: {
            const unreachable: never = violation;
            throw new Error(`unhandled size ceiling violation: ${JSON.stringify(unreachable)}`);
        }
    }
}

// A key holding a backslash never matches, so an escaped spelling of an existing key is reported unreadable.
const WRITTEN_CEILING_ENTRY = /^ {4}"([^"\\]+)": -?\d[\d.eE+-]*,?$/;

/**
 * The keys of the formatted ceilings file in written order, repeats included, which `JSON.parse` would
 * collapse. Matches one `"path": number` entry per line; a line it cannot read yields no key, so callers
 * also require listUnreadableCeilingLines to return nothing.
 */
export function listWrittenCeilingKeys(text: string): string[] {
    return text.split('\n').flatMap((line) => WRITTEN_CEILING_ENTRY.exec(line)?.[1] ?? []);
}

function isStructuralLine(line: string, index: number, lines: readonly string[]): boolean {
    const last = lines.length - 1;
    return (index === 0 && line === '{') || (index === last - 1 && line === '}') || (index === last && line === '');
}

/** Every line, in written order, that is neither the object's braces, the final empty line, nor an entry. */
export function listUnreadableCeilingLines(text: string): string[] {
    return text
        .split('\n')
        .filter((line, index, lines) => !isStructuralLine(line, index, lines) && !WRITTEN_CEILING_ENTRY.test(line));
}

function isCeilingRecord(value: unknown): value is Record<string, number> {
    if (typeof value !== 'object' || value === null || Array.isArray(value)) {
        return false;
    }
    return Object.values(value).every((entry) => typeof entry === 'number');
}

/** Reads the recorded ceilings from the tree rooted at `repoRoot`. */
export function readSizeCeilings(repoRoot: string): Record<string, number> {
    const parsed: unknown = JSON.parse(readFileSync(resolve(repoRoot, SIZE_CEILINGS_PATH), 'utf8'));
    if (!isCeilingRecord(parsed)) {
        throw new Error(`${SIZE_CEILINGS_PATH} must be one flat object mapping each path to a number.`);
    }
    return parsed;
}

/** Counts newline characters, as `wc -l` does, in the file at `path` relative to `repoRoot`. */
export function countFileLines(repoRoot: string, path: string): number {
    return readFileSync(resolve(repoRoot, path), 'utf8').split('\n').length - 1;
}

export type SizeBaselineGrowth = {
    addedPaths: string[];
    addedCeilingKeys: string[];
    removedCeilingKeys: string[];
    raisedCeilings: { path: string; from: number; to: number }[];
};

export type SizeBaselineSnapshot = {
    baselineFiles: readonly string[];
    ceilings: Readonly<Record<string, number>>;
};

/** Everything the head added to the size baseline or raised, relative to the base; paths and ceilings may only leave or go down. */
export function findSizeBaselineGrowth(base: SizeBaselineSnapshot, head: SizeBaselineSnapshot): SizeBaselineGrowth {
    const basePaths = new Set(base.baselineFiles);
    const headCeilingKeys = Object.keys(head.ceilings);
    const headPaths = new Set(head.baselineFiles);
    return {
        addedPaths: head.baselineFiles.filter((path) => !basePaths.has(path)),
        addedCeilingKeys: headCeilingKeys.filter((path) => !Object.hasOwn(base.ceilings, path)),
        // A key may leave with its path (a burn-down); dropping it while the path stays exempts the file from every limit.
        removedCeilingKeys: Object.keys(base.ceilings).filter(
            (path) => headPaths.has(path) && !Object.hasOwn(head.ceilings, path)
        ),
        raisedCeilings: headCeilingKeys.flatMap((path) => {
            if (!Object.hasOwn(base.ceilings, path)) {
                return [];
            }
            const from = base.ceilings[path];
            const to = head.ceilings[path];
            return from !== undefined && to !== undefined && to > from ? [{ path, from, to }] : [];
        }),
    };
}

/** One instruction per finding, in the order a future author reads them. */
export function describeSizeBaselineGrowth(growth: SizeBaselineGrowth): string[] {
    return [
        ...growth.addedPaths.map(
            (path) =>
                `${path}: added to eslint.size-baseline.mjs; no file is ever added. Split the file below the size rules instead.`
        ),
        ...growth.addedCeilingKeys.map(
            (path) => `${path}: new ceiling in ${SIZE_CEILINGS_PATH}; ceilings exist only for files already baselined.`
        ),
        ...growth.removedCeilingKeys.map(
            (path) =>
                `${path}: ceiling removed from ${SIZE_CEILINGS_PATH} while the file is still baselined; it would then grow unchecked.`
        ),
        ...growth.raisedCeilings.map(
            ({ path, from, to }) =>
                `${path}: ceiling raised from ${from} to ${to} in ${SIZE_CEILINGS_PATH}; ceilings are never raised.`
        ),
    ];
}

/**
 * The paths quoted inside the `sizeBaselineFiles` array literal of the baseline module's text, read as text so
 * the base's code is never evaluated. Only quoted strings, commas, whitespace and comments may appear inside the
 * array; any other token (template literal, spread, identifier, nested bracket) throws, because a form this reader
 * cannot see would be dropped from the comparison. Throws when no array is found; an empty array is a fully burned-down base and reads as no paths.
 */
export function parseSizeBaselineFilesText(text: string): string[] {
    const declaration = /\bsizeBaselineFiles\s*=\s*\[/.exec(text);
    if (declaration === null) {
        throw new Error('no sizeBaselineFiles array found in the baseline text.');
    }
    const paths: string[] = [];
    let index = declaration.index + declaration[0].length;
    while (index < text.length && text.charAt(index) !== ']') {
        const char = text.charAt(index);
        if (/[\s,]/.test(char)) {
            index += 1;
        } else if (text.startsWith('//', index)) {
            const newline = text.indexOf('\n', index);
            index = newline === -1 ? text.length : newline + 1;
        } else if (text.startsWith('/*', index)) {
            const close = text.indexOf('*/', index + 2);
            if (close === -1) {
                throw new Error('unterminated block comment in the sizeBaselineFiles array.');
            }
            index = close + 2;
        } else if (char === "'" || char === '"') {
            const close = text.indexOf(char, index + 1);
            const value = close === -1 ? '' : text.slice(index + 1, close);
            if (close === -1 || value.includes('\n') || value.includes('\\')) {
                throw new Error(`unreadable string at offset ${index} in the sizeBaselineFiles array.`);
            }
            paths.push(value);
            index = close + 1;
        } else {
            throw new Error(
                `unsupported token ${JSON.stringify(text.slice(index, index + 12))} in the sizeBaselineFiles array; only quoted strings and comments are readable.`
            );
        }
    }
    if (index >= text.length) {
        throw new Error('the sizeBaselineFiles array is not closed.');
    }
    return paths;
}

/** Parses ceilings text with the same shape check `readSizeCeilings` applies to the file. */
export function parseSizeCeilingsText(text: string): Record<string, number> {
    const parsed: unknown = JSON.parse(text);
    if (!isCeilingRecord(parsed)) {
        throw new Error(`${SIZE_CEILINGS_PATH} must be one flat object mapping each path to a number.`);
    }
    return parsed;
}
