import { findDeviceTarget } from './llmActionStrategies/bridgeArgumentGuards';

export type DeviceBatchTarget = {
    deviceId: string | null;
    trackId: string;
    kind: 'add' | 'remove' | 'update';
};

type ActionOf<Type extends RuntimeActionType> = Extract<RuntimeAction, { type: Type }>;
type DeviceBatchTargetLookup = {
    readonly [Type in RuntimeActionType]: (action: ActionOf<Type>, context: ProjectContext) => DeviceBatchTarget | null;
};

function noDeviceBatchTarget(): DeviceBatchTarget | null {
    return null;
}

function existingDeviceTarget(kind: DeviceBatchTarget['kind']) {
    return (
        action: ActionOf<'removeDevice' | 'setDeviceParameter' | 'bypassDevice'>,
        context: ProjectContext
    ): DeviceBatchTarget | null => {
        const target = findDeviceTarget(context, action.payload.deviceId);
        if (!target) {
            return null;
        }
        return { deviceId: target.device.id, trackId: target.track.id, kind };
    };
}

