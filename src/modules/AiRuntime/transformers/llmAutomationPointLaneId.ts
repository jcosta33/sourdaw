function lookupAutomationPointLaneId<Type extends RuntimeActionType>(action: ActionOf<Type>): string | null {
    if (!Object.hasOwn(automationPointLaneIdByActionType, action.type)) {
        return noAutomationPointLane();
    }
    return automationPointLaneIdByActionType[action.type](action);
}

/** The automation lane a single point write lands on. */
export function getAutomationPointLaneId(action: RuntimeAction): string | null {
    return lookupAutomationPointLaneId(action);
}
