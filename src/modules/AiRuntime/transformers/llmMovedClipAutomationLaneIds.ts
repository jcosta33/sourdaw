function lookupMovedClipAutomationLaneIds<Type extends RuntimeActionType>(
    action: ActionOf<Type>,
    context: ProjectContext
): string[] {
    if (!Object.hasOwn(movedClipAutomationLaneIdsByActionType, action.type)) {
        return noMovedAutomationLanes();
    }
    return movedClipAutomationLaneIdsByActionType[action.type](action, context);
}

/** Automation lanes that ride along on the clips an action moves. */
export function getMovedClipAutomationLaneIds(action: RuntimeAction, context: ProjectContext): string[] {
    return lookupMovedClipAutomationLaneIds(action, context);
}
