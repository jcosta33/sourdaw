// ── Clamp helper ─────────────────────────────────────────────────────────

export function clampNumber(val: unknown, min: number, max: number, fallback: number): number {
    if (typeof val !== 'number' || !Number.isFinite(val)) {
        return fallback;
    }
    return Math.max(min, Math.min(max, val));
}

