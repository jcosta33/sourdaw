function lookupClipDestinationTrackIds<Type extends RuntimeActionType>(action: ActionOf<Type>): string[] {
    if (!Object.hasOwn(clipDestinationTrackIdsByActionType, action.type)) {
        return noDestinationTracks();
    }
    return clipDestinationTrackIdsByActionType[action.type](action);
}

/** Tracks an action places clips on, beyond the tracks of the clips it names. */
export function getClipDestinationTrackIds(action: RuntimeAction): string[] {
    return lookupClipDestinationTrackIds(action);
}
