function lookupSplitDuplicateSubjects<Type extends RuntimeActionType>(action: ActionOf<Type>): SplitDuplicateSubjects {
    if (!Object.hasOwn(splitDuplicateSubjectsByActionType, action.type)) {
        return noSubjects;
    }
    return splitDuplicateSubjectsByActionType[action.type](action);
}

/** The clips and tracks an action splits, duplicates, glues or adds clips to, for batch conflict checks. */
export function getSplitDuplicateSubjects(action: RuntimeAction): SplitDuplicateSubjects {
    return lookupSplitDuplicateSubjects(action);
}
