import { type AppActionType } from '#/utils/handlerContract';

/**
 * What an automation action touches when its payload names no track and parameter pair. A range write
 * touches one parameter on every declared owner; a mode change touches every lane its owners hold.
 */
type AutomationFallbackScope =
    | { kind: 'none' }
    | { kind: 'ownerLanes' }
    | { kind: 'ownerParameter'; parameterId: (payload: Readonly<Record<string, unknown>>) => string };

export const noFallbackScope: AutomationFallbackScope = { kind: 'none' };
const ownerLanes: AutomationFallbackScope = { kind: 'ownerLanes' };
const gainParameter: AutomationFallbackScope = { kind: 'ownerParameter', parameterId: () => 'gain' };
const sendParameter: AutomationFallbackScope = {
    kind: 'ownerParameter',
    parameterId: (payload) => `send:${String(payload.busId)}`,
};

