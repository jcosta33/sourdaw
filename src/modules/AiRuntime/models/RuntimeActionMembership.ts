export type RuntimeActionType = {
    [Type in AppActionType]: (typeof runtimeActionMembershipByActionType)[Type] extends true ? Type : never;
}[AppActionType];

function isAppActionType(type: string): type is AppActionType {
    return Object.hasOwn(runtimeActionMembershipByActionType, type);
}

export function isRuntimeActionType(type: string): type is RuntimeActionType {
    return isAppActionType(type) && runtimeActionMembershipByActionType[type];
}

export const RUNTIME_ACTION_TYPES: readonly RuntimeActionType[] = Object.keys(
    runtimeActionMembershipByActionType
).filter(isRuntimeActionType);
