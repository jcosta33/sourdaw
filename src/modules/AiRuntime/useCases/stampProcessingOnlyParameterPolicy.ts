import { type AutomationRecordingPolicy } from '#/modules/Automation/events';
import { type AppAction, type AppActionType } from '#/utils/handlerContract';

type ActionOf<Type extends AppActionType> = Extract<AppAction, { type: Type }>;
type Stamp = { readonly [Type in AppActionType]: (action: ActionOf<Type>) => AppAction };

const PROCESSING_ONLY_POLICY: AutomationRecordingPolicy = 'suppressed';

function leaveUnstamped(action: AppAction): AppAction {
    return action;
}

function stampSetDeviceParameter(action: ActionOf<'setDeviceParameter'>): AppAction {
    if (action.payload.automationRecordingPolicy === PROCESSING_ONLY_POLICY) {
        return action;
    }
    return {
        type: 'setDeviceParameter',
        payload: { ...action.payload, automationRecordingPolicy: PROCESSING_ONLY_POLICY },
    };
}

function stampSetTrackGain(action: ActionOf<'setTrackGain'>): AppAction {
    if (action.payload.automationRecordingPolicy === PROCESSING_ONLY_POLICY) {
        return action;
    }
    return {
        type: 'setTrackGain',
        payload: { ...action.payload, automationRecordingPolicy: PROCESSING_ONLY_POLICY },
    };
}

function stampSetTrackPan(action: ActionOf<'setTrackPan'>): AppAction {
    if (action.payload.automationRecordingPolicy === PROCESSING_ONLY_POLICY) {
        return action;
    }
    return {
        type: 'setTrackPan',
        payload: { ...action.payload, automationRecordingPolicy: PROCESSING_ONLY_POLICY },
    };
}

