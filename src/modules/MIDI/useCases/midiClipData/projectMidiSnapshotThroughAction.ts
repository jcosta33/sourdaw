import { type AppAction, type AppActionType } from '#/utils/handlerContract';

type ActionOf<Type extends AppActionType> = Extract<AppAction, { type: Type }>;

export type ProjectedMidiSnapshot = {
    notes: { present: boolean; value: readonly unknown[] };
    controlChanges: { present: boolean; value: readonly unknown[] };
    pitchBends: { present: boolean; value: readonly unknown[] };
};

function unchangedSnapshot(_action: unknown, _clipId: string, snapshot: ProjectedMidiSnapshot): ProjectedMidiSnapshot {
    return snapshot;
}

function afterRemoveClip(
    action: ActionOf<'removeClip'>,
    clipId: string,
    snapshot: ProjectedMidiSnapshot
): ProjectedMidiSnapshot {
    if (action.payload.clipId !== clipId) {
        return snapshot;
    }
    return {
        notes: { present: false, value: [] },
        controlChanges: { present: false, value: [] },
        pitchBends: { present: false, value: [] },
    };
}

function afterRestoreClip(
    action: ActionOf<'restoreClip'>,
    clipId: string,
    snapshot: ProjectedMidiSnapshot
): ProjectedMidiSnapshot {
    if (action.payload.clipId !== clipId) {
        return snapshot;
    }
    const payload = action.payload;
    let notes = snapshot.notes;
    let controlChanges = snapshot.controlChanges;
    let pitchBends = snapshot.pitchBends;
    if (payload.midiNotesSnapshot !== null) {
        notes = { present: true, value: payload.midiNotesSnapshot };
    }
    if (payload.midiCcSnapshot !== null) {
        controlChanges = { present: true, value: payload.midiCcSnapshot };
    }
    if (payload.midiPitchBendSnapshot !== null) {
        pitchBends = { present: true, value: payload.midiPitchBendSnapshot };
    }
    return { notes, controlChanges, pitchBends };
}

function afterRestoreClipSplitState(
    action: ActionOf<'restoreClipSplitState'>,
    clipId: string,
    snapshot: ProjectedMidiSnapshot
): ProjectedMidiSnapshot {
    let projected = snapshot;
    if (action.payload.clipId === clipId) {
        projected = action.payload.replacement.sourceMidi;
    }
    if (action.payload.rightClipId === clipId) {
        projected = action.payload.replacement.rightMidi;
    }
    return projected;
}

