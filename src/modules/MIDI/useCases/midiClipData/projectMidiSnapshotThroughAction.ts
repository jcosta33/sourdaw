function lookup<Type extends AppActionType>(
    action: ActionOf<Type>,
    clipId: string,
    snapshot: ProjectedMidiSnapshot
): ProjectedMidiSnapshot {
    return midiSnapshotByActionType[action.type](action, clipId, snapshot);
}

/** One clip's MIDI data as it stands after an earlier batch action ran. */
export function projectMidiSnapshotThroughAction(
    action: AppAction,
    clipId: string,
    snapshot: ProjectedMidiSnapshot
): ProjectedMidiSnapshot {
    return lookup(action, clipId, snapshot);
}
