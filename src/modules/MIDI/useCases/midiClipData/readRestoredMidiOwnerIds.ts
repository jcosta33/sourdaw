function lookup<Type extends AppActionType>(action: ActionOf<Type>): readonly string[] {
    return restoredMidiOwnerIdsByActionType[action.type](action);
}

/** The clip ids whose MIDI data an earlier batch action restores, in the order it restores them. */
export function readRestoredMidiOwnerIds(action: AppAction): readonly string[] {
    return lookup(action);
}
