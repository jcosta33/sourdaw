type ActionOf<Type extends AppActionType> = Extract<AppAction, { type: Type }>;

function noOwnerIds(): readonly string[] {
    return [];
}

function clipOwnerIds(action: ActionOf<'restoreClip'>): readonly string[] {
    return [action.payload.clipId];
}

function splitOwnerIds(action: ActionOf<'restoreClipSplitState'>): readonly string[] {
    return [action.payload.clipId, action.payload.rightClipId];
}

