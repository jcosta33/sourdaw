function lookup<Type extends AppActionType>(action: ActionOf<Type>): MidiReplayProducer {
    return midiReplayProducerByActionType[action.type](action);
}

/** Whether an earlier batch action creates a clip or a track, and which. */
export function classifyMidiReplayProducer(action: AppAction): MidiReplayProducer {
    return lookup(action);
}
