import { type AppAction, type AppActionType } from '#/utils/handlerContract';

type ActionOf<Type extends AppActionType> = Extract<AppAction, { type: Type }>;

type MidiReplayProducer =
    | { readonly kind: 'clip'; readonly action: ActionOf<'addClip'> }
    | { readonly kind: 'track'; readonly action: ActionOf<'addTrack'> }
    | { readonly kind: 'none' };

function producesClip(action: ActionOf<'addClip'>): MidiReplayProducer {
    return { kind: 'clip', action };
}

function producesTrack(action: ActionOf<'addTrack'>): MidiReplayProducer {
    return { kind: 'track', action };
}

function producesNothing(): MidiReplayProducer {
    return { kind: 'none' };
}

