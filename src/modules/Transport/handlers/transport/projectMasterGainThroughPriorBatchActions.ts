import { resolveLevelFields, TRACK_FADER_LAW } from '#/utils/audioLevelLaw';
import { type AppAction, type AppActionType, type HandlerValidationContext } from '#/utils/handlerContract';

import { MAX_MASTER_GAIN } from '../../stores/transportStore';

type ActionOf<Type extends AppActionType> = Extract<AppAction, { type: Type }>;

function keepMasterPercent(_action: unknown, projected: number): number {
    return projected;
}

// A restore writes the replacement percent directly, with no law to resolve against.
function projectRestoredMasterGain(action: ActionOf<'restoreMasterGain'>): number {
    return action.payload.replacementPercent;
}

function projectSetMasterGain(action: ActionOf<'setMasterGain'>, projected: number): number {
    const resolved = resolveLevelFields(
        { linear: action.payload.gain, absoluteDb: action.payload.gainDb, deltaDb: action.payload.deltaDb },
        projected / 100,
        TRACK_FADER_LAW
    );
    if (!resolved.ok) {
        return projected;
    }
    // `replaceMasterGain` refuses a percent outside `[0, MAX_MASTER_GAIN]`
    // rather than storing it, so the projection bounds the same way — a
    // later action's `deltaDb` in this batch must measure from a percent
    // the store could actually hold.
    return Math.max(0, Math.min(MAX_MASTER_GAIN, resolved.linear * 100));
}

