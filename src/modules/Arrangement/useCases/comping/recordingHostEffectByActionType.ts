function applyHostEffect<Type extends AppActionType>(action: ActionOf<Type>, hostIds: Set<string>): void {
    if (!Object.hasOwn(recordingHostEffectByActionType, action.type)) {
        leaveHosts();
        return;
    }
    recordingHostEffectByActionType[action.type](action, hostIds);
}

/** Applies one prior action's effect on which tracks can host a recording lane. */
export function applyRecordingHostEffect(action: AppAction, hostIds: Set<string>): void {
    applyHostEffect(action, hostIds);
}
