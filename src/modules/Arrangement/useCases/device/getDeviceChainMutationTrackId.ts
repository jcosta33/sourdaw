function lookup<Type extends AppActionType>(action: ActionOf<Type>, currentStep: Track): string | undefined {
    if (!Object.hasOwn(deviceChainMutationTrackIdByActionType, action.type)) {
        return undefined;
    }
    return deviceChainMutationTrackIdByActionType[action.type](action, currentStep);
}

export function getDeviceChainMutationTrackId(action: AppAction, currentStep: Track): string | undefined {
    return lookup(action, currentStep);
}
