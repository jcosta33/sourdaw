import { type AppAction, type AppActionType } from '#/utils/handlerContract';

type ActionOf<Type extends AppActionType> = Extract<AppAction, { type: Type }>;

function retiresNoClip(_action: unknown): string[] {
    return [];
}

function retiresRemovedClip(action: ActionOf<'discardDuplicatedClip' | 'removeClip'>): string[] {
    return [action.payload.clipId];
}

function retiresSplitRightClip(action: ActionOf<'restoreClipSplitState'>): string[] {
    if (action.payload.replacement.rightClip) {
        return [];
    }
    return [action.payload.rightClipId];
}

