/** The clip ids a completed prefix action retires. */
export function retiredClipIds<Type extends AppActionType>(action: ActionOf<Type>): string[] {
    if (!Object.hasOwn(retiredClipIdsByActionType, action.type)) {
        return retiresNoClip(action);
    }
    return retiredClipIdsByActionType[action.type](action);
}
