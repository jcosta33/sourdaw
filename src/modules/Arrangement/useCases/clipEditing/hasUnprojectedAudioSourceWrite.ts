function lookup<Type extends AppActionType>(action: ActionOf<Type>, state: ClipOwners): boolean {
    if (!Object.hasOwn(hasUnprojectedAudioSourceWriteByActionType, action.type)) {
        return noUnprojectedWrite();
    }
    return hasUnprojectedAudioSourceWriteByActionType[action.type](action, state);
}

/** These source writers do not yet provide a prepared value to this prefix.
 * Refuse overlapping audio combinations before effects instead of reading an
 * earlier programme as though the operation had not happened. */
export function hasUnprojectedAudioSourceWrite(action: AppAction, state: ClipOwners): boolean {
    return lookup(action, state);
}
