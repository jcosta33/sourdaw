import { type AppAction, type AppActionType } from '#/utils/handlerContract';

import { type LocatedClip } from './ShiftedOwnerState';

type ActionOf<Type extends AppActionType> = Extract<AppAction, { type: Type }>;
type ClipOwners = { readonly clips: readonly LocatedClip[] };

function isAudioClip(clip: LocatedClip['clip']): boolean {
    return 'type' in clip && clip.type === 'audio';
}

function noUnprojectedWrite(): boolean {
    return false;
}

function clipWriteOverlapsAudioClip(
    action: Extract<
        AppAction,
        {
            type:
                | 'trimClipStart'
                | 'trimClipEnd'
                | 'slipClipContent'
                | 'moveClip'
                | 'restoreClipPlacement'
                | 'reverseClip'
                | 'setClipLoop'
                | 'restoreClipLoop'
                | 'setClipLoopLength'
                | 'restoreClipLoopLength'
                | 'setClipStretchMode'
                | 'setClipStretchRatio'
                | 'restoreClipStretchState';
        }
    >,
    state: ClipOwners
): boolean {
    return state.clips.some((owner) => owner.clip.id === action.payload.clipId && isAudioClip(owner.clip));
}

function compRegionOverlapsAudioClip(
    action: Extract<AppAction, { type: 'setCompRegion' | 'removeCompRegion' | 'restoreCompRegionInterval' }>,
    state: ClipOwners
): boolean {
    return state.clips.some(
        (owner) =>
            owner.owningTrackId === action.payload.trackId &&
            isAudioClip(owner.clip) &&
            owner.clip.endBeat > action.payload.startBeat &&
            (action.payload.endBeat === undefined || owner.clip.startBeat < action.payload.endBeat)
    );
}

function trackHasAudioClip(
    action: Extract<AppAction, { type: 'selectTake' | 'switchTrackAlternative' }>,
    state: ClipOwners
): boolean {
    return state.clips.some((owner) => owner.owningTrackId === action.payload.trackId && isAudioClip(owner.clip));
}

