type ActionOf<Type extends AppActionType> = Extract<AppAction, { type: Type }>;

function keepState(_action: unknown, state: ShiftedOwnerState): ShiftedOwnerState {
    return state;
}

function projectRelink(action: ActionOf<'relinkClipAudioSources'>, state: ShiftedOwnerState): ShiftedOwnerState | null {
    if (!state.tracks) {
        return null;
    }
    const tracks = projectRelinkAudioSourceTracks(state.tracks, [action]);
    if (!tracks) {
        return null;
    }
    return {
        ...state,
        tracks,
        clips: tracks.flatMap((track) => track.clips.map((clip) => ({ owningTrackId: track.id, clip }))),
    };
}

function projectDiscard(
    action: Extract<AppAction, { type: 'discardDuplicatedClip' }>,
    state: ShiftedOwnerState
): ShiftedOwnerState | null {
    const clipId = action.payload.clipId;
    if (!state.clips.some((owner) => owner.clip.id === clipId)) {
        return null;
    }
    return {
        ...state,
        clips: state.clips.filter((owner) => owner.clip.id !== clipId),
        lanes: state.lanes.filter((lane) => lane.clipId !== clipId),
    };
}

