function lookup<Type extends AppActionType>(
    action: ActionOf<Type>,
    state: ShiftedOwnerState,
    trackIds: readonly string[]
): ShiftedOwnerState | null {
    if (!Object.hasOwn(projectClipActionByActionType, action.type)) {
        return keepState(action, state);
    }
    return projectClipActionByActionType[action.type](action, state, trackIds);
}

export function projectClipAction(
    state: ShiftedOwnerState,
    action: AppAction,
    trackIds: readonly string[]
): ShiftedOwnerState | null {
    if (hasUnprojectedAudioSourceWrite(action, state)) {
        // Geometry-only guards cannot claim a complete source model.
        state = { ...state, tracks: null };
    }
    state = { ...state, tracks: tracksWithProjectedClips(state) };
    return lookup(action, state, trackIds);
}
