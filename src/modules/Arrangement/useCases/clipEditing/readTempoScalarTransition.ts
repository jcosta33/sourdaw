function notATempoAction(): undefined {
    return undefined;
}

/** The transition that undoes this tempo edit, or null when the edit carries no tempo change identity to undo it by. */
function reverseTempoTransition(
    action: Extract<AppAction, { type: 'setTempo' | 'restoreTempoEdit' }>
): TempoScalarTransition | null {
    const { bpm, expectedBpm, tempoChangeId } = action.payload;
    if (tempoChangeId === undefined || expectedBpm === undefined) {
        return null;
    }
    return { tempoChangeId, expectedBpm: bpm, bpm: expectedBpm };
}

