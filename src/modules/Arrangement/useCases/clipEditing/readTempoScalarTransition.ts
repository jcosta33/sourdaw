function lookup<Type extends AppActionType>(action: ActionOf<Type>): TempoScalarTransition | null | undefined {
    return tempoScalarTransitionByActionType[action.type](action);
}

/** The reverse tempo-scalar transition of an earlier batch action: undefined when the action is not a tempo
 * edit, null when it is one that cannot be reversed. */
export function readTempoScalarTransition(action: AppAction): TempoScalarTransition | null | undefined {
    return lookup(action);
}
