type ActionOf<Type extends AppActionType> = Extract<AppAction, { type: Type }>;

function projectRestoredDevice(action: ActionOf<'restoreDevice'>, devices: Device[]): Device[] {
    devices.splice(action.payload.deviceIndex, 0, structuredClone(action.payload.deviceSnapshot));
    return devices;
}

function projectWrittenDevice(action: ActionOf<'setDeviceParameter' | 'setDeviceState'>, devices: Device[]): Device[] {
    projectDeviceWrite(
        devices.find((candidate) => candidate.id === action.payload.deviceId),
        action
    );
    return devices;
}

