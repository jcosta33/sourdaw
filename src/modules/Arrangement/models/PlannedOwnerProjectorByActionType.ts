function lookup<Type extends AppActionType>(
    action: ActionOf<Type>,
    owners: Owner[],
    plugins: readonly PluginDescriptor[]
): OwnerProjection {
    if (!Object.hasOwn(plannedOwnerProjectorByActionType, action.type)) {
        return projectEveryOwner(action, owners, plugins);
    }
    return plannedOwnerProjectorByActionType[action.type](action, owners, plugins);
}

export function projectCommandOwners(
    owners: Owner[],
    action: AppAction,
    plugins: readonly PluginDescriptor[]
): OwnerProjection {
    return lookup(action, owners, plugins);
}
