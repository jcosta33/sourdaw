function lookup<Type extends AppActionType>(action: ActionOf<Type>, tracks: PlannedTrackName[]): PlannedTrackName[] {
    if (!Object.hasOwn(trackNameProjectionByActionType, action.type)) {
        return tracks;
    }
    return trackNameProjectionByActionType[action.type](action, tracks);
}

export function projectTrackNames(tracks: PlannedTrackName[], action: AppAction): PlannedTrackName[] {
    return lookup(action, tracks);
}
