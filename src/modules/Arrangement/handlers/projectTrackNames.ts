import { type AppAction, type AppActionType } from '#/utils/handlerContract';

import { nextDefaultTrackName } from '../models/DefaultTrackName';

type ActionOf<Type extends AppActionType> = Extract<AppAction, { type: Type }>;

export type PlannedTrackName = { readonly id?: string; readonly kind: string; readonly name: string };

const trackKinds: ReadonlySet<string> = new Set(['audio', 'midi', 'bus', 'master', 'folder']);

function restoredTrackName(action: ActionOf<'restoreTrack'>): PlannedTrackName {
    const snapshot: unknown = action.payload.trackSnapshot;
    if (
        typeof snapshot !== 'object' ||
        snapshot === null ||
        Array.isArray(snapshot) ||
        !('id' in snapshot) ||
        typeof snapshot.id !== 'string' ||
        snapshot.id.length === 0 ||
        snapshot.id !== action.payload.trackId ||
        !('kind' in snapshot) ||
        typeof snapshot.kind !== 'string' ||
        !trackKinds.has(snapshot.kind) ||
        !('name' in snapshot) ||
        typeof snapshot.name !== 'string'
    ) {
        throw new TypeError('Cannot plan a default track name from a malformed restored track');
    }
    return { id: snapshot.id, kind: snapshot.kind, name: snapshot.name };
}

function keepTrackNames(_action: unknown, tracks: PlannedTrackName[]): PlannedTrackName[] {
    return tracks;
}

function projectAddedTrackName(action: ActionOf<'addTrack'>, tracks: PlannedTrackName[]): PlannedTrackName[] {
    return [
        ...tracks,
        {
            id: action.payload.id,
            kind: action.payload.kind,
            name: action.payload.name ?? nextDefaultTrackName(action.payload.kind, tracks),
        },
    ];
}

function projectCreatedBusName(action: ActionOf<'createBus'>, tracks: PlannedTrackName[]): PlannedTrackName[] {
    return [...tracks, { id: action.payload.busId, kind: 'bus', name: action.payload.name }];
}

function projectRenamedTrack(action: ActionOf<'renameTrack'>, tracks: PlannedTrackName[]): PlannedTrackName[] {
    return tracks.map((track) => {
        if (track.id !== action.payload.trackId) {
            return track;
        }
        return { ...track, name: action.payload.name };
    });
}

function projectRemovedTrackName(
    action: ActionOf<'removeTrack' | 'discardCreatedTrack'>,
    tracks: PlannedTrackName[]
): PlannedTrackName[] {
    return tracks.filter((track) => track.id !== action.payload.trackId || track.kind === 'master');
}

function projectRestoredTrackName(action: ActionOf<'restoreTrack'>, tracks: PlannedTrackName[]): PlannedTrackName[] {
    return [...tracks, restoredTrackName(action)];
}

