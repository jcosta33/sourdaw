function lookup<Type extends AppActionType>(action: ActionOf<Type>): AutomationRecordingPolicy | undefined {
    if (!Object.hasOwn(automationRecordingPolicyByActionType, action.type)) {
        return noPolicy();
    }
    return automationRecordingPolicyByActionType[action.type](action);
}

/** The policy an action carries, or `undefined` for every action that cannot carry one. */
export function getActionAutomationRecordingPolicy(action: AppAction): AutomationRecordingPolicy | undefined {
    return lookup(action);
}
