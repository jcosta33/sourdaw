function lookup<Type extends AppActionType>(action: ActionOf<Type>): readonly ClipSatelliteEntrySnapshot[] | undefined {
    if (!Object.hasOwn(clipSatelliteReplacementByActionType, action.type)) {
        return noReplacements();
    }
    return clipSatelliteReplacementByActionType[action.type](action);
}

/** The satellite entries a prior action replaces, or `undefined` for every action that replaces none. */
export function getClipSatelliteReplacements(action: AppAction): readonly ClipSatelliteEntrySnapshot[] | undefined {
    return lookup(action);
}
