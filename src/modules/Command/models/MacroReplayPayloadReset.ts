import { type AppAction, type AppActionType } from '#/utils/handlerContract';

type ActionOf<Type extends AppActionType> = Extract<AppAction, { type: Type }>;

export function keepRecordedPayload(action: AppAction): AppAction {
    return action;
}

// A public history reversion can record restoration-only hints. Macro playback uses the fresh
// command law against today's clip and rows; its handler captures that execution for its own
// exact Undo and Redo.
function dropSlipRestorationHints(action: ActionOf<'slipClipContent'>): AppAction {
    delete action.payload.midiRowCoordinates;
    delete action.payload.rowLiftBeats;
    return action;
}

function dropTrimRestorationHints(action: ActionOf<'trimClipStart'>): AppAction {
    delete action.payload.midiRowCoordinates;
    delete action.payload.midiOffsetBeats;
    delete action.payload.loopOriginBeat;
    return action;
}

// The recorded copy id was consumed by the recorded gesture's undo: on replay the copy still
// exists, so the pinned id would make the handler no-write and the step would silently vanish.
// Clearing it lets the handler mint a fresh copy, like every create.
function dropRecordedCopyId(action: ActionOf<'duplicateClipAt'>): AppAction {
    delete action.payload.targetClipId;
    return action;
}

// The recorded plan names the ids the recorded gesture created and the project it read; the
// handler keeps a carried plan and refuses it once stale. A replay is a new gesture, so clear the
// plan and let the handler plan it against the project as it now is.
function dropGluePlan(action: ActionOf<'glueClips'>): AppAction {
    delete action.payload.expected;
    delete action.payload.replacement;
    delete action.payload.targetClipId;
    return action;
}

function dropStripSilencePlan(action: ActionOf<'stripSilence'>): AppAction {
    delete action.payload.expected;
    delete action.payload.replacement;
    return action;
}

// As above: the recorded plan names the recorded slices and the source it detected; a replay plans
// again against the project as it now is.
function dropTransientPlan(action: ActionOf<'quantizeTransients'>): AppAction {
    delete action.payload.plan;
    return action;
}

// The recorded template and note revision belong to the recorded gesture; a replay extracts again
// from the clip's notes as they now are.
function dropGrooveRevision(action: ActionOf<'extractGroove'>): AppAction {
    const { clipId, templateId, sourceName, subdivision } = action.payload;
    return { type: 'extractGroove', payload: { clipId, templateId, sourceName, subdivision } };
}

// A reverted section removal records a slot that belongs to the section list it was recorded
// against, so replay appends like a fresh public request.
function dropRecordedSectionIndex(action: ActionOf<'addSection'>): AppAction {
    delete action.payload.index;
    return action;
}

