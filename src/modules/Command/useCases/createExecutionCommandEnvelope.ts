function materializeSeed<Type extends AppActionType>(action: ActionOf<Type>): SeedMaterialization {
    if (!Object.hasOwn(seedMaterializerByActionType, action.type)) {
        return leaveSeedUnminted(action);
    }
    return seedMaterializerByActionType[action.type](action);
}

function isRecord(value: unknown): value is Readonly<Record<string, unknown>> {
    return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function getPayloadRecord(action: AppAction): Readonly<Record<string, unknown>> {
    if (!('payload' in action) || !isRecord(action.payload)) {
        return {};
    }
    return action.payload;
}

/**
 * The assigned ids `materializeCommandApplicationIds` drew before the handler ran, plus the ids the
 * handler or the state guards drew into the arguments this command compiled.
 */
function withCompiledMintedIds(
    operation: string,
    argumentsValue: Readonly<Record<string, unknown>>,
    assigned: readonly CommandApplicationAssignedId[]
): readonly CommandApplicationAssignedId[] {
    const minted = readHandlerMintedApplicationIds(operation, argumentsValue).filter(
        (entry) => !assigned.some((existing) => existing.argument === entry.argument)
    );
    return [...assigned, ...minted];
}

export function createExecutionCommandEnvelope(input: CreateExecutionCommandEnvelopeInput): {
    action: AppAction;
    envelope: VersionedCommandEnvelope;
} {
    const identityMaterialized = input.applicationAssignedIds
        ? { action: input.action, applicationAssignedIds: input.applicationAssignedIds }
        : materializeCommandApplicationIds(input.action);
    const materialized = materializeSeed(identityMaterialized.action);
    const source = input.options?.source ?? 'manual';
    const argumentsValue = getPayloadRecord(materialized.action);
    const metadata = compileCommandArgumentMetadata(argumentsValue, materialized.action.type);
    const envelope = createVersionedCommandEnvelope({
        action: materialized.action,
        applicationAssignedIds: withCompiledMintedIds(
            materialized.action.type,
            argumentsValue,
            identityMaterialized.applicationAssignedIds
        ),
        availableDeviceVersions: commandDeviceVersionsPort.capture({
            argumentsValue,
            operation: materialized.action.type,
        }),
        dependencyIds: input.dependencyIds,
        expectedEffect: input.expectedEffect,
        groupId: input.options?.groupId,
        normalizedProjectRevision: input.normalizedProjectRevision ?? commandProjectRevisionPort.capture(),
        objectReferences: metadata.objectReferences,
        parameterUnits: metadata.parameterUnits,
        reason: `Execute ${materialized.action.type} from ${source}`,
        seed: materialized.seed,
        time: metadata.time,
    });
    return { action: materialized.action, envelope };
}
