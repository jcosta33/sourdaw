type ActionOf<Type extends AppActionType> = Extract<AppAction, { type: Type }>;

type StochasticAction = ActionOf<
    'generateChordProgression' | 'generateDrumPattern' | 'generateMelody' | 'humanizeNotes'
>;

type SeedMaterialization = { action: AppAction; seed?: number };

function leaveSeedUnminted(action: AppAction): SeedMaterialization {
    return { action };
}

function mintSeed(action: StochasticAction): SeedMaterialization {
    if (action.payload.seed !== undefined) {
        return { action, seed: action.payload.seed };
    }
    const cloned = structuredClone(action);
    const seed = generateSeed();
    cloned.payload.seed = seed;
    return { action: cloned, seed };
}

