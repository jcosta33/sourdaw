function isKnownActionType(operation: string): operation is AppActionType {
    return Object.hasOwn(REQUIRED_ID_ARGUMENTS, operation);
}

export function getRequiredApplicationAssignedIdArguments(
    operation: string,
    argumentsValue: CommandArguments
): string[] {
    if (!isKnownActionType(operation)) {
        return [];
    }
    const required = REQUIRED_ID_ARGUMENTS[operation];
    if (required !== null) {
        return required(argumentsValue);
    }
    const rule = COMMAND_APPLICATION_ID_RULES[operation];
    if (!rule || typeof argumentsValue[rule.argument] !== 'string') {
        return [];
    }
    return [rule.argument];
}
