import { type AppActionType } from '#/utils/handlerContract';

type SupportPathPredicate = (path: string) => boolean;

const noSupportPath = null;

function isTempoEditSupportPath(path: string): boolean {
    return path === 'audioSourcePromotion' || path.startsWith('audioSourcePromotion.');
}

function isTempoMapEditSupportPath(path: string): boolean {
    return path === 'rowPlan' || path.startsWith('rowPlan.') || isTempoEditSupportPath(path);
}

function isCompRegionSupportPath(path: string): boolean {
    return (
        path.startsWith('audioSourcePromotions[') || /^(expected|replacement)\[\d+\]\.audioSource(?:\.|$)/.test(path)
    );
}

