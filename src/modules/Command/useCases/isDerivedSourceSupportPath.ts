function isKnownActionType(operation: string): operation is AppActionType {
    return Object.hasOwn(DERIVED_SOURCE_SUPPORT_PATHS, operation);
}

export function isDerivedSourceSupportPath(operation: string | undefined, path: string): boolean {
    if (operation === undefined || !isKnownActionType(operation)) {
        return false;
    }
    return DERIVED_SOURCE_SUPPORT_PATHS[operation]?.(path) ?? false;
}
