function getExtraTargetIds<Type extends AppActionType>(action: ActionOf<Type>): readonly string[] {
    if (!Object.hasOwn(extraTargetsByActionType, action.type)) {
        return noExtraTargets();
    }
    return extraTargetsByActionType[action.type](action);
}

export function getCommandDivergenceTargetIds(input: {
    actions: readonly AppAction[];
    targetIds: readonly string[];
}): string[] {
    const targetIds = new Set(input.targetIds);
    for (const action of input.actions) {
        const payload = action.payload;
        if (typeof payload === 'object' && payload !== null && !Array.isArray(payload)) {
            for (const reference of compileCommandArgumentMetadata(payload).objectReferences) {
                // A brief's ids are intent, not targets: an edit to a track it names is no drift, and
                // the brief's own handler refuses a write naming an object the project no longer holds.
                if (!isRecordedIntentPath(action.type, reference.argument)) {
                    targetIds.add(reference.id);
                }
            }
        }
        for (const extraTargetId of getExtraTargetIds(action)) {
            targetIds.add(extraTargetId);
        }
    }
    return [...targetIds];
}
